#!/usr/bin/env python3
"""Build step for Variant B (Fireplace).

Usage:  python3 -I tools/build_b.py <path-to-original-task-repo> <path-to-this-repo>

What it does (see DECISIONS.md for the reasoning):
  1. backgrounds: left/right = the delivered per-part files (they match design/layout.png), re-encoded;
     top = a 1:1 crop of bg-big.jpg taken at the same scale and offset as the left part, so the
     left|top seam is pixel-continuous (the delivered top/bg.jpg is bg-big zoomed by 1.32).
  2. RESTORES TRANSPARENCY. box.png, cta.png and left/right hl.png were exported as palette PNGs
     *without* a tRNS chunk, i.e. opaque on black. The palette index order still carries the
     original alpha ramp (0 = clear ... last = opaque), so alpha is rebuilt from the index.
     box.png is a flat 1-bit mask, its real opacity/colour is fitted to design/layout.png.
  3. crops every layer to its bounding box (smaller files, less overdraw) and writes
     css/positions.css with the exact CSS position of each crop (2x pixels / 2).
"""
import os, sys
import numpy as np
from PIL import Image

SRC, DST = sys.argv[1], sys.argv[2]
S = os.path.join(SRC, "variant-b-fireplace", "assets")
D = os.path.join(DST, "variant-b-fireplace", "assets")
for sub in ("top", "left", "right"):
    os.makedirs(os.path.join(D, sub), exist_ok=True)

css = ["/* generated by tools/build_b.py - do not edit. All values are CSS px (= asset px / 2). */"]
total = 0
def size(p):
    global total
    total += os.path.getsize(p)

def rule(sel, x, y, w, h):
    css.append(f"{sel} {{ left: {x/2:g}px; top: {y/2:g}px; width: {w/2:g}px; height: {h/2:g}px; }}")

def save_crop(rgba, box, path, sel):
    x0, y0, x1, y1 = box
    im = Image.fromarray(rgba[y0:y1, x0:x1], "RGBA")
    im.save(path, optimize=True); size(path)
    rule(sel, x0, y0, x1 - x0, y1 - y0)

def bbox(alpha, thr=3, pad=6, even=True, w=None, h=None):
    ys, xs = np.where(alpha > thr)
    x0, y0, x1, y1 = xs.min() - pad, ys.min() - pad, xs.max() + 1 + pad, ys.max() + 1 + pad
    if even:
        x0 -= x0 % 2; y0 -= y0 % 2; x1 += x1 % 2; y1 += y1 % 2
    return max(0, x0), max(0, y0), min(w or 10**9, x1), min(h or 10**9, y1)

# ------------------------------------------------------------------ 1. backgrounds
big = Image.open(os.path.join(S, "bg-big.jpg")).convert("RGB")
# delivered left/bg.jpg == bg-big shifted by (4, 12) px (measured with SIFT, scale 1.000, 2600 inliers).
# the top part starts 8 px (4 css px) right of the left part and spans 2064 px.
top = big.crop((4 + 640 + 8, 12, 4 + 640 + 8 + 2064, 12 + 500))
top.save(os.path.join(D, "top", "bg.jpg"), quality=80, optimize=True, progressive=True); size(os.path.join(D, "top", "bg.jpg"))
for part in ("left", "right"):
    im = Image.open(os.path.join(S, part, "bg.jpg")).convert("RGB")
    p = os.path.join(D, part, "bg.jpg")
    im.save(p, quality=80, optimize=True, progressive=True); size(p)
print("backgrounds written")

# ------------------------------------------------------------------ 2. alpha restoration
def palette_rgba(path, kind):
    im = Image.open(path)
    pal = np.array(im.getpalette()[: 3 * (im.getextrema()[1] + 1)], dtype=np.uint8).reshape(-1, 3)
    idx = np.array(im)
    rgb = pal[idx]
    n = idx.max()
    if kind == "ramp-from-index":                    # hl.png: white text, indices 0..n = alpha 0..1
        a = (idx.astype(float) / n)
    elif kind == "cta":                              # idx0 clear, idx1-6 = red corner anti-aliasing, 7+ opaque
        a = np.where(idx == 0, 0.0, np.where(idx < 7, idx / 7.0, 1.0))
    out = np.dstack([rgb, np.round(a * 255).astype(np.uint8)])
    out[a == 0, :3] = 0
    return out

# --- text panel: 1-bit mask; colour + opacity fitted to design/layout.png (G/B channels, slope fit)
PANEL_RGB, PANEL_ALPHA = (48, 106, 156), 0.91
box = np.array(Image.open(os.path.join(S, "box.png")))
rows = np.where(box.any(axis=1))[0]
r0, r1 = int(rows.min()), int(rows.max()) + 1
r0 += r0 % 2; r1 += r1 % 2
band = np.zeros((r1 - r0, 640, 4), np.uint8)
band[..., :3] = PANEL_RGB; band[..., 3] = int(round(PANEL_ALPHA * 255))
for part in ("left", "right"):
    p = os.path.join(D, part, "panel.png")
    Image.fromarray(band, "RGBA").save(p, optimize=True); size(p)
rule(".panel", 0, r0, 640, r1 - r0)
print(f"panel rows {r0}-{r1} -> css top {r0/2:g}, height {(r1-r0)/2:g}")

# --- CTA button
cta = palette_rgba(os.path.join(S, "cta.png"), "cta")
p = os.path.join(D, "cta.png"); Image.fromarray(cta, "RGBA").save(p, optimize=True); size(p)
css.append(f".cta {{ width: {cta.shape[1]/2:g}px; height: {cta.shape[0]/2:g}px; }}")

# --- copy text of the skyscrapers
for part in ("left", "right"):
    hl = palette_rgba(os.path.join(S, part, "hl.png"), "ramp-from-index")
    save_crop(hl, bbox(hl[..., 3], pad=6, w=640, h=1950), os.path.join(D, part, "copy.png"), f".{part} .copy")

# --- logos (already RGBA)
for part in ("left", "right"):
    lg = np.array(Image.open(os.path.join(S, part, "logo.png")).convert("RGBA"))
    save_crop(lg, bbox(lg[..., 3], pad=2, w=640, h=1950), os.path.join(D, part, "logo.png"), f".{part} .logo")

# --- top headline: split into its three lines (cut in the empty rows between them, even rows)
th = np.array(Image.open(os.path.join(S, "top", "hl.png")).convert("RGBA"))
core = (th[..., 3] > 128).sum(axis=1) > 0
runs, start = [], None
for y, v in enumerate(core):
    if v and start is None: start = y
    if not v and start is not None and (y - start) > 5: runs.append((start, y)); start = None
    if not v and start is not None and (y - start) <= 5: start = None
if start is not None: runs.append((start, len(core)))
assert len(runs) == 3, runs
cuts = [0] + [((runs[i][1] + runs[i + 1][0]) // 2) // 2 * 2 for i in range(2)] + [th.shape[0]]
cols = np.where(th[..., 3].max(axis=0) > 3)[0]
x0, x1 = int(cols.min()) - 4, int(cols.max()) + 5
x0 -= x0 % 2; x1 += x1 % 2
for i in range(3):
    y0, y1 = cuts[i], cuts[i + 1]
    save_crop(th, (x0, y0, x1, y1), os.path.join(D, "top", f"line{i+1}.png"), f".top .line{i+1}")
print("headline lines (2x rows):", cuts)

open(os.path.join(DST, "variant-b-fireplace", "css", "positions.css"), "w").write("\n".join(css) + "\n")
print(f"assets written: {total/1024:.0f} KB (without the 73 KB GSAP)")
